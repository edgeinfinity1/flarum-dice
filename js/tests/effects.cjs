const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync(__dirname+'/../src/common/effects.js','utf8').replace(/export function /g,'function ');
const sandbox={};vm.runInNewContext(source+';this.api={effects,iconType,cssVariables,resolveIcon,previewRolls}',sandbox);
const {effects,iconType,cssVariables,resolveIcon,previewRolls}=sandbox.api;const cfg=JSON.parse(fs.readFileSync(__dirname+'/../../resources/defaults.json','utf8'));
let count=0;const check=(v,label)=>{assert.ok(v,label);count++;};
check(effects(1,20,20,cfg).includes('success'),'d20 max success');
check(effects(1,20,1,cfg).includes('failure'),'d20 min failure');
check(!effects(1,6,6,cfg).includes('success'),'d6 no critical');
check(effects(1,100,100,cfg).includes('success'),'default maximum only');
check(!effects(1,100,99,cfg).includes('success'),'second largest not critical');
check(effects(1,100,99,{...cfg,criticalCount:2}).includes('success'),'configurable two highest outcomes');
check(!effects(1,100,95,cfg).includes('success'),'boundary excluded');
check(effects(-10,10,-1,cfg).includes('negative'),'negative range');
check(effects(-10,10,0,cfg).includes('zero'),'zero');
check(!effects(-10,-1,-5,cfg).includes('negative'),'single sign excluded');
check(effects(1,1000,666,cfg)[0]==='special','priority');
check(effects(1,1000,666,cfg).includes('repeat'),'repeat also shown');
check(effects(-1000,1000,-123,cfg).includes('sequence'),'absolute sequence');
check(!effects(1,1000,890,cfg).includes('sequence'),'no wrap sequence');
check(iconType(1,4)==='d4'&&iconType(2,5)==='generic'&&iconType(1,5)==='generic','exact icon ranges');
check(effects(1,20,1,{...cfg,successHigh:false}).includes('success'),'low is success');
check(effects(1,20,NaN,cfg).length===0,'invalid result');
check(cssVariables(cfg,'success')['--edge-dice-text-dark']===cfg.colors.success.dark.text,'dark color');
const colors=JSON.parse(JSON.stringify(cfg));colors.colors.normal.light.icon='#123456';
check(!cssVariables(colors,'success')['--edge-dice-icon-light'],'blank effect icon follows its own text');
check(cssVariables(colors,'normal')['--edge-dice-icon-light']==='#123456','normal icon remains configurable');
check(effects(2,2,2,cfg).length===0,'single-outcome range has no critical effect');
check(effects(-1000000000,1000000000,1000000000,cfg).includes('success'),'maximum supported range');
check(effects(1,1000,321,cfg).includes('sequence'),'descending digits');
check(!effects(1,1000,12,cfg).includes('sequence'),'minimum digits respected');
check(resolveIcon(1,8,false,cfg).type==='builtin','d8 builtin enabled');
check(resolveIcon(1,8,true,cfg).value==='far fa-question','edited icon overrides special');
check(resolveIcon(1,8,true,{...cfg,markEdited:false}).type==='builtin','marker toggle restores special');
check(resolveIcon(5,10,false,cfg).value==='far fa-dice','default generic configurable');
const icons=JSON.parse(JSON.stringify(cfg));icons.specialIcons['8'].enabled=false;
check(resolveIcon(1,8,false,icons).value==='far fa-dice','per-die opt out');
icons.specialIcons['8']={enabled:true,type:'image',value:'/dice.png'};
check(resolveIcon(1,8,false,icons).type==='image','custom image');
const old=[{min:1,max:20,result:17,edited:false},{min:1,max:6,result:2,edited:false},{min:1,max:20,result:4,edited:false}];
const ranges=[{min:1,max:20},{min:0,max:0},{min:1,max:20}];
const previews=previewRolls(old,ranges,cfg);
check(previews[0].result===17&&previews[1].result===null&&previews[2].result===4,'edit preview FIFO reuse without new result');
check(previews.every(d=>d.edited),'edit preview selection-risk marking');
check(previewRolls(old,ranges,{...cfg,allowEdit:false}).every(d=>d.state==='invalid-edit'),'strict mode preview');
console.log(JSON.stringify({passed:count}));
